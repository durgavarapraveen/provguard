#!/usr/bin/env sh
# Write the Homebrew formula, Scoop manifest and winget manifests for a
# release, from its SHA256SUMS.
# Usage: scripts/packaging.sh <version> [SHA256SUMS file, default dist/SHA256SUMS]
# Output: packaging/homebrew/provguard.rb, bucket/provguard.json,
#         packaging/winget/<version>/*.yaml
set -eu
version=${1:?usage: scripts/packaging.sh <version> [SHA256SUMS]}
version=${version#v}
sums=${2:-dist/SHA256SUMS}
repo=https://github.com/durgavarapraveen/provguard
base=$repo/releases/download/v$version

sum() { # sum <file name>: its SHA-256 from $sums
  h=$(awk -v f="$1" '{ n = $2; sub(/^\*/, "", n) } n == f { print $1 }' "$sums")
  [ -n "$h" ] || { echo "packaging.sh: no checksum for $1 in $sums" >&2; exit 1; }
  printf '%s' "$h"
}
upper() { printf '%s' "$1" | tr 'a-f' 'A-F'; }

mac_arm=$(sum "provguard_${version}_darwin_arm64")
mac_amd=$(sum "provguard_${version}_darwin_amd64")
lin_arm=$(sum "provguard_${version}_linux_arm64")
lin_amd=$(sum "provguard_${version}_linux_amd64")
win_amd=$(sum "provguard_${version}_windows_amd64.exe")
win_arm=$(sum "provguard_${version}_windows_arm64.exe")

mkdir -p packaging/homebrew bucket "packaging/winget/$version"

cat > packaging/homebrew/provguard.rb <<RB
# Generated by scripts/packaging.sh. Copy to the tap repository
# durgavarapraveen/homebrew-provguard as Formula/provguard.rb.
class Provguard < Formula
  desc "Runtime firewall for AI coding agents"
  homepage "$repo"
  version "$version"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$base/provguard_${version}_darwin_arm64"
      sha256 "$mac_arm"
    end
    on_intel do
      url "$base/provguard_${version}_darwin_amd64"
      sha256 "$mac_amd"
    end
  end

  on_linux do
    on_arm do
      url "$base/provguard_${version}_linux_arm64"
      sha256 "$lin_arm"
    end
    on_intel do
      url "$base/provguard_${version}_linux_amd64"
      sha256 "$lin_amd"
    end
  end

  def install
    bin.install Dir["provguard_*"].first => "provguard"
  end

  def caveats
    <<~EOS
      Turn protection on for your coding agents:
        provguard init
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/provguard version")
  end
end
RB

cat > bucket/provguard.json <<JSON
{
    "version": "$version",
    "description": "Runtime firewall for AI coding agents",
    "homepage": "$repo",
    "license": "Apache-2.0",
    "architecture": {
        "64bit": {
            "url": "$base/provguard_${version}_windows_amd64.exe#/provguard.exe",
            "hash": "$win_amd"
        },
        "arm64": {
            "url": "$base/provguard_${version}_windows_arm64.exe#/provguard.exe",
            "hash": "$win_arm"
        }
    },
    "bin": "provguard.exe",
    "notes": "Turn protection on for your coding agents: provguard init",
    "checkver": "github",
    "autoupdate": {
        "architecture": {
            "64bit": {
                "url": "$repo/releases/download/v\$version/provguard_\$version_windows_amd64.exe#/provguard.exe"
            },
            "arm64": {
                "url": "$repo/releases/download/v\$version/provguard_\$version_windows_arm64.exe#/provguard.exe"
            }
        },
        "hash": {
            "url": "\$baseurl/SHA256SUMS"
        }
    }
}
JSON

id=DurgavaraPraveen.Provguard
w=packaging/winget/$version
cat > "$w/$id.yaml" <<YAML
# Generated by scripts/packaging.sh.
PackageIdentifier: $id
PackageVersion: $version
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.6.0
YAML
cat > "$w/$id.installer.yaml" <<YAML
# Generated by scripts/packaging.sh.
PackageIdentifier: $id
PackageVersion: $version
InstallerType: portable
Commands:
- provguard
Installers:
- Architecture: x64
  InstallerUrl: $base/provguard_${version}_windows_amd64.exe
  InstallerSha256: $(upper "$win_amd")
- Architecture: arm64
  InstallerUrl: $base/provguard_${version}_windows_arm64.exe
  InstallerSha256: $(upper "$win_arm")
ManifestType: installer
ManifestVersion: 1.6.0
YAML
cat > "$w/$id.locale.en-US.yaml" <<YAML
# Generated by scripts/packaging.sh.
PackageIdentifier: $id
PackageVersion: $version
PackageLocale: en-US
Publisher: durgavarapraveen
PublisherUrl: https://github.com/durgavarapraveen
PackageName: provguard
PackageUrl: $repo
License: Apache-2.0
LicenseUrl: $repo/blob/main/LICENSE
ShortDescription: Runtime firewall for AI coding agents
Description: provguard is a hook for AI coding agents such as Claude Code, Cursor and Codex. It stops secret leaks and prompt-injection attacks. Run provguard init after you install it.
ReleaseNotesUrl: $repo/releases/tag/v$version
Tags:
- security
- ai-agents
- claude-code
- prompt-injection
- cli
ManifestType: defaultLocale
ManifestVersion: 1.6.0
YAML

echo "wrote packaging/homebrew/provguard.rb, bucket/provguard.json, $w/"
